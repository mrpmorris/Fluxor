namespace Fluxor.SourceGenerator.UnitTests;

/// <summary>
/// The FLXG001 descriptor, the Fluxor versions the generator supports, and the shape of the generated class.
/// </summary>
public class GeneratorOutputTests
{
	private const string GeneratedFileName = "FluxorGeneratedRegistration.g.cs";

	private static readonly string[] RequiredFluxorTypes =
	{
		"namespace Fluxor { public interface IFeature<TState> : IFeature { } }",
		"namespace Fluxor { public interface IReducer<TState> { } }",
		"namespace Fluxor { public interface IEffect { } }",
		"namespace Fluxor { public interface IMiddleware { } }",
		"namespace Fluxor { public interface IDispatcher { } }",
		"namespace Fluxor { public class FeatureStateAttribute : System.Attribute { } }",
		"namespace Fluxor { public class ReducerMethodAttribute : System.Attribute { } }",
		"namespace Fluxor { public class EffectMethodAttribute : System.Attribute { } }",
		"namespace Fluxor.DependencyInjection.Generated { public sealed class FluxorGeneratedRegistrationAttribute : System.Attribute { } }",
		"namespace Fluxor.DependencyInjection.Generated { public interface IFluxorGeneratedRegistration { } }",
		"namespace Fluxor.DependencyInjection.Generated { public static class GeneratedWrappers { } }",
		"namespace Fluxor.DependencyInjection.Generated { public static class GeneratedRegistrationTable { } }",
	};

	public static TheoryData<int> MissingFluxorTypes => new(Enumerable.Range(0, RequiredFluxorTypes.Length));

	[Theory]
	[MemberData(nameof(MissingFluxorTypes))]
	public void WhenReferencedFluxorLacksATypeTheGeneratorNeeds_ThenFLXG001SaysFluxorIsNotSupported(int missing)
	{
		ImmutableArray<Diagnostic> diagnostics = RunAgainstFluxor(RequiredFluxorTypes.Where((_, index) => index != missing));

		Diagnostic diagnostic = Assert.Single(diagnostics);
		Assert.Equal("FLXG001", diagnostic.Id);
		Assert.Equal(Location.None, diagnostic.Location);
		Assert.Equal(
			"This assembly (the referenced Fluxor does not support generated registration) cannot be registered by generated code;"
				+ " this assembly uses the reflection scan",
			diagnostic.GetMessage(CultureInfo.InvariantCulture));
	}

	[Fact]
	public void WhenReferencedFluxorHasEveryTypeTheGeneratorNeeds_ThenNoFLXG001()
	{
		Assert.Empty(RunAgainstFluxor(RequiredFluxorTypes));
	}

	[Fact]
	public void WhenNoFluxorIsReferenced_ThenNothingIsReportedOrGenerated()
	{
		(Compilation output, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "namespace Ns; public class Plain { }" },
			"true",
			referenceFluxor: false);

		Assert.Empty(diagnostics);
		Assert.DoesNotContain(output.SyntaxTrees, x => x.FilePath.EndsWith(GeneratedFileName, StringComparison.Ordinal));
	}

	[Fact]
	public void WhenFLXG001IsReported_ThenItIsAnEnabledFluxorWarning()
	{
		(_, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "using Fluxor; namespace Ns; [FeatureState] public record Missing(int X);" },
			optIn: true);

		DiagnosticDescriptor descriptor = Assert.Single(diagnostics).Descriptor;
		Assert.Equal("FLXG001", descriptor.Id);
		Assert.Equal("Fluxor", descriptor.Category);
		Assert.Equal(DiagnosticSeverity.Warning, descriptor.DefaultSeverity);
		Assert.True(descriptor.IsEnabledByDefault);
	}

	[Fact]
	public void WhenRegistrationIsGenerated_ThenItIsMarkedAsGeneratedCodeAndBuildsItsEntriesOnce()
	{
		const string source = """
			using Fluxor;
			namespace Ns;
			[FeatureState]
			public record S(int Value)
			{
				public S() : this(0) { }
			}
			""";
		(Compilation output, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(new[] { source }, optIn: true);
		Assert.Empty(diagnostics);

		string generated = Assert.Single(output.SyntaxTrees, x => x.FilePath.EndsWith(GeneratedFileName, StringComparison.Ordinal)).ToString();
		Assert.StartsWith("// <auto-generated/>", generated);

		Assembly assembly = GeneratorTestHost.LoadAssembly(output);
		Type registrationType = assembly.GetCustomAttribute<FluxorGeneratedRegistrationAttribute>().RegistrationType;
		Assert.Equal("Fluxor.SourceGenerator", registrationType.GetCustomAttribute<GeneratedCodeAttribute>()?.Tool);
		Assert.Equal(EditorBrowsableState.Never, registrationType.GetCustomAttribute<EditorBrowsableAttribute>()?.State);
		Assert.False(registrationType.IsPublic);

		var first = (IFluxorGeneratedRegistration)Activator.CreateInstance(registrationType);
		var second = (IFluxorGeneratedRegistration)Activator.CreateInstance(registrationType);
		Assert.Same(first.Types, second.Types);
	}

	/// <summary>
	/// Generated code calls what it can call (no reflection); only what it cannot call is reached the way
	/// FeatureStateInfo reaches it. Either way the feature starts with the state the scan would create.
	/// </summary>
	[Theory]
	[InlineData("[FeatureState] public record S(int Value) { public S() : this(1) { } }", false, "S { Value = 1 }")]
	[InlineData("[FeatureState] public class S { public int Field = 2; public int Property { get; set; } = 3; public override string ToString() => $\"{Field} {Property}\"; }", false, "2 3")]
	[InlineData("[FeatureState(CreateInitialStateMethodName = nameof(Create))] public record S(int Value) { public static S Create() => new(1); }", false, "S { Value = 1 }")]
	[InlineData("[FeatureState] public record S(int Value) { private S() : this(4) { } }", true, "S { Value = 4 }")]
	[InlineData("[FeatureState] public class S { [System.Obsolete(\"old\", true)] public S() { } public override string ToString() => \"obsolete\"; }", true, "obsolete")]
	[InlineData("[FeatureState] public class S { public required int Value { get; init; } public override string ToString() => \"required \" + Value; }", true, "required 0")]
	[InlineData("[FeatureState] public class S { public required int Value; public override string ToString() => \"required field \" + Value; }", true, "required field 0")]
	[InlineData("[FeatureState(CreateInitialStateMethodName = nameof(Create))] public record S(int Value) { private static S Create() => new(5); }", true, "S { Value = 5 }")]
	[InlineData("[FeatureState(CreateInitialStateMethodName = nameof(Create))] public record S(int Value) { [System.Obsolete(\"old\", true)] public static S Create() => new(6); }", true, "S { Value = 6 }")]
	public void WhenStateIsGenerated_ThenItsInitialStateIsCreatedWithoutReflectionWhenGeneratedCodeCanDoSo(
		string state,
		bool usesReflection,
		string initialState)
	{
		(Compilation output, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "using Fluxor; namespace Ns; " + state },
			optIn: true);
		Assert.Empty(diagnostics);
		Assert.Empty(output.GetDiagnostics().Where(x => x.Severity == DiagnosticSeverity.Error));

		// What the generated code calls
		SyntaxTree generated = Assert.Single(output.SyntaxTrees, x => x.FilePath.EndsWith(GeneratedFileName, StringComparison.Ordinal));
		SemanticModel model = output.GetSemanticModel(generated);
		string[] reflectionCalls = generated.GetRoot().DescendantNodes()
			.OfType<Microsoft.CodeAnalysis.CSharp.Syntax.InvocationExpressionSyntax>()
			.Select(x => model.GetSymbolInfo(x).Symbol as IMethodSymbol)
			.Where(x => x is not null)
			.Select(x => x.ContainingType.ToDisplayString() + "." + x.Name)
			.Where(x => x.StartsWith("System.Activator.", StringComparison.Ordinal)
				|| x.StartsWith("System.Type.", StringComparison.Ordinal)
				|| x.StartsWith("System.Reflection.", StringComparison.Ordinal))
			.ToArray();
		Assert.Equal(usesReflection, reflectionCalls.Length > 0);

		// What the feature starts with
		Assembly assembly = GeneratorTestHost.LoadAssembly(output);
		Type registrationType = assembly.GetCustomAttribute<FluxorGeneratedRegistrationAttribute>().RegistrationType;
		var registration = (IFluxorGeneratedRegistration)Activator.CreateInstance(registrationType);
		GeneratedTypeEntry entry = Assert.Single(registration.Types, x => x.FeatureState is not null);
		Assert.Equal(initialState, entry.FeatureState.CreateFeature(entry.FeatureState.StateIndex).GetState().ToString());
	}

	[Theory]
	[InlineData("App", "App.FluxorGenerated")]
	[InlineData("My-App.1st", "My_App._1st.FluxorGenerated")]
	[InlineData("a..b", "a._.b.FluxorGenerated")]
	[InlineData("class.Lib", "class.Lib.FluxorGenerated")]
	[InlineData(null, "Assembly.FluxorGenerated")]
	public void WhenAssemblyNameIsNotACSharpNamespace_ThenGeneratedNamespaceIsMadeValid(string assemblyName, string expectedNamespace)
	{
		(Compilation output, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "using Fluxor; namespace Ns; [FeatureState] public record S(int Value) { public S() : this(1) { } }" },
			"true",
			assemblyName: assemblyName);

		Assert.Empty(diagnostics);
		Assert.Empty(output.GetDiagnostics().Where(x => x.Severity == DiagnosticSeverity.Error));
		// The registration type the assembly attribute points to
		AttributeData attribute = Assert.Single(
			output.Assembly.GetAttributes(),
			x => x.AttributeClass?.Name == nameof(FluxorGeneratedRegistrationAttribute));
		var registrationType = (INamedTypeSymbol)attribute.ConstructorArguments[0].Value;
		Assert.Equal(
			expectedNamespace,
			registrationType.ContainingNamespace.ToDisplayString(
				new SymbolDisplayFormat(typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces)));

		// An assembly without a name cannot be emitted; every other one loads and is read by the runtime
		if (assemblyName is not null)
		{
			Assembly assembly = GeneratorTestHost.LoadAssembly(output);
			Type loaded = assembly.GetCustomAttribute<FluxorGeneratedRegistrationAttribute>().RegistrationType;
			Assert.Equal(expectedNamespace, loaded.Namespace);
		}
	}

	[Theory]
	[InlineData("appsettings.json")]
	[InlineData("Pages/Counter.razor.css")]
	[InlineData("Pages/Counter.razor.js")]
	public void WhenAdditionalFileIsNotARazorFile_ThenItIsNotLookedAt(string path)
	{
		(Compilation output, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "using Fluxor; namespace Ns; public class ComponentWithEffects : Effect<string> { public override System.Threading.Tasks.Task HandleAsync(string a, IDispatcher d) => System.Threading.Tasks.Task.CompletedTask; }" },
			"true",
			additionalTexts: new[] { new GeneratorTestHost.InMemoryAdditionalText(path, "@inherits ComponentWithEffects [EffectMethod]") });

		Assert.Empty(diagnostics);
		Assert.Contains(output.SyntaxTrees, x => x.FilePath.EndsWith(GeneratedFileName, StringComparison.Ordinal));
	}

	[Theory]
	[InlineData("Pages/Counter.razor")]
	[InlineData("Pages/Counter.RAZOR")]
	[InlineData("Pages/Counter.cshtml")]
	[InlineData("Pages/Counter.CSHTML")]
	public void WhenAdditionalFileIsARazorFile_ThenItIsLookedAt(string path)
	{
		(_, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "using Fluxor; namespace Ns; public class ComponentWithEffects : Effect<string> { public override System.Threading.Tasks.Task HandleAsync(string a, IDispatcher d) => System.Threading.Tasks.Task.CompletedTask; }" },
			"true",
			additionalTexts: new[] { new GeneratorTestHost.InMemoryAdditionalText(path, "@inherits ComponentWithEffects") });

		Diagnostic diagnostic = Assert.Single(diagnostics);
		Assert.StartsWith(path + " (a Razor file that mentions ComponentWithEffects;", diagnostic.GetMessage(CultureInfo.InvariantCulture));
	}

	private static ImmutableArray<Diagnostic> RunAgainstFluxor(IEnumerable<string> fluxorTypes)
	{
		Compilation fluxor = GeneratorTestHost.CreateCompilation(
			fluxorTypes.Prepend("namespace Fluxor { public interface IFeature { } }").ToArray(),
			assemblyName: "Fluxor",
			referenceFluxor: false);

		(_, ImmutableArray<Diagnostic> diagnostics) = GeneratorTestHost.Run(
			new[] { "namespace Ns; public class Plain { }" },
			"true",
			new[] { GeneratorTestHost.CreateReference(fluxor) },
			referenceFluxor: false);
		return diagnostics;
	}
}
