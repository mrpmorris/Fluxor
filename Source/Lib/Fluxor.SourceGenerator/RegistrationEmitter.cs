using Microsoft.CodeAnalysis.CSharp;
using System.Text;

namespace Fluxor.SourceGenerator;

/// <summary>
/// Writes a <see cref="RegistrationModel"/> as an <c>IFluxorGeneratedRegistration</c> class plus the assembly
/// attribute pointing to it. The code has O(hosts + types / 256) methods and no lambdas (except one per state whose
/// initial-state factory method is not accessible to generated code), since the number of methods is what costs
/// time on first call (JIT on CoreCLR, the interpreter on WebAssembly): the entries are described by a table of
/// ints (stored as data, not code) that GeneratedRegistrationTable turns into descriptors, with the types it refers
/// to filled in by a few methods of at most <see cref="MaxTypesPerMethod"/> <c>typeof</c> each. Each host class
/// has one factory method that creates its reducers (or effects) by index, and the feature creation, initial state
/// and AddReducer calls are one switch each for the whole assembly. Reducers and effects are bound as method groups,
/// so each delegate's <c>Method</c> is the real method. The code is plain C# that compiles with older language
/// versions too.
/// </summary>
internal static class RegistrationEmitter
{
	public const string HintName = "FluxorGeneratedRegistration.g.cs";
	public const string ClassName = "FluxorGeneratedRegistration";

	/// <summary>The value of FluxorGeneratedRegistrationFormat.Current this emitter writes.</summary>
	public const int FormatVersion = 1;

	/// <summary>At most this many <c>typeof</c> per method that fills the type table.</summary>
	public const int MaxTypesPerMethod = 256;

	private const string GeneratedNamespace = "global::Fluxor.DependencyInjection.Generated";
	private const string TypeEntry = GeneratedNamespace + ".GeneratedTypeEntry";
	private const string Wrappers = GeneratedNamespace + ".GeneratedWrappers";
	private const string IFeature = "global::Fluxor.IFeature";
	private const string IEffect = "global::Fluxor.IEffect";
	private const string ReducerFactory = "global::System.Func<object, int, object>";
	private const string EffectFactory = "global::System.Func<object, int, " + IEffect + ">";

	public static string Emit(RegistrationModel model)
	{
		var code = new CodeWriter();
		var states = new StateTable(model);

		code.Line("// <auto-generated/>");
		code.Line(
			"#pragma warning disable "
			+ string.Join(", ", new[] { "CS0612", "CS0618" }.Concat(model.SuppressedDiagnosticIds))
			+ " // Obsolete members are registered, as the reflection scan does");
		code.Line();
		code.Line(
			"[assembly: " + GeneratedNamespace + ".FluxorGeneratedRegistration(typeof(global::" + model.Namespace + "." + ClassName + "), "
			+ FormatVersion + ")]");
		code.Line();
		code.Line("namespace " + model.Namespace);
		code.Open();
		code.Line("/// <summary>The Fluxor registration of this assembly, generated at build time.</summary>");
		code.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"Fluxor.SourceGenerator\", \"" + FormatVersion + "\")]");
		code.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		code.Line("internal sealed class " + ClassName + " : " + GeneratedNamespace + ".IFluxorGeneratedRegistration");
		code.Open();
		code.Line("private static readonly " + TypeEntry + "[] TypesValue = CreateTypes();");
		code.Line();
		code.Line("public " + ClassName + "() { }");
		code.Line();
		code.Line("public global::System.Collections.Generic.IReadOnlyList<" + TypeEntry + "> Types => TypesValue;");

		CompactEmitter.Emit(code, model, states);

		code.Close();
		code.Close();
		return code.ToString();
	}

	/// <summary>
	/// The state types that have a feature (a <c>[FeatureState]</c> or a feature class), numbered in order of
	/// first appearance; the number is the state index the descriptors carry.
	/// </summary>
	private sealed class StateTable
	{
		private readonly Dictionary<string, int> IndexByStateType = new(StringComparer.Ordinal);

		public StateTable(RegistrationModel model)
		{
			foreach (TypeEntryModel entry in model.Entries)
			{
				if (entry.FeatureClass is { } featureClass)
					Add(featureClass.StateType);
				if (entry.FeatureState is { } featureState)
				{
					Add(featureState.StateType);
					FeatureStates.Add(featureState);
				}
			}
		}

		/// <summary>State types in index order.</summary>
		public List<string> StateTypes { get; } = new();

		/// <summary>The <c>[FeatureState]</c> states, in entry order.</summary>
		public List<FeatureStateModel> FeatureStates { get; } = new();

		public int this[string stateType] => IndexByStateType[stateType];

		private void Add(string stateType)
		{
			if (IndexByStateType.ContainsKey(stateType))
				return;
			IndexByStateType.Add(stateType, StateTypes.Count);
			StateTypes.Add(stateType);
		}
	}

	private static class CompactEmitter
	{
		private const string Table = GeneratedNamespace + ".GeneratedRegistrationTable";

		public static void Emit(CodeWriter code, RegistrationModel model, StateTable states)
		{
			var types = new List<string>();
			var typeIndexes = new Dictionary<string, int>(StringComparer.Ordinal);
			int TypeIndex(string type)
			{
				if (!typeIndexes.TryGetValue(type, out int index))
				{
					index = types.Count;
					typeIndexes.Add(type, index);
					types.Add(type);
				}
				return index;
			}

			var reducerFactories = new List<int>();
			var effectFactories = new List<int>();
			var table = new List<string>();
			for (int i = 0; i < model.Entries.Count; i++)
			{
				TypeEntryModel entry = model.Entries[i];
				var values = new List<int> { TypeIndex(entry.Type), GetFlags(entry) };
				if (entry.FeatureClass is { } featureClass)
					values.AddRange(new[]
					{
						TypeIndex(featureClass.StateType),
						TypeIndex(IFeature + "<" + featureClass.StateType + ">"),
						states[featureClass.StateType]
					});
				if (entry.FeatureState is { } featureState)
					values.AddRange(new[]
					{
						TypeIndex(featureState.StateType),
						TypeIndex(IFeature + "<" + featureState.StateType + ">"),
						states[featureState.StateType]
					});
				if (entry.ReducerClassStateType is { } reducerClassStateType)
					values.Add(TypeIndex(reducerClassStateType));

				values.Add(entry.ReducerMethods.Count);
				if (entry.ReducerMethods.Count > 0)
				{
					values.Add(reducerFactories.Count);
					reducerFactories.Add(i);
					foreach (ReducerMethodModel reducer in entry.ReducerMethods)
						values.Add(TypeIndex(reducer.StateType) * 2 + (reducer.IsStatic ? 1 : 0));
				}

				values.Add(entry.EffectMethods.Count);
				if (entry.EffectMethods.Count > 0)
				{
					values.Add(effectFactories.Count);
					effectFactories.Add(i);
					foreach (EffectMethodModel effect in entry.EffectMethods)
						values.Add(effect.IsStatic ? 1 : 0);
				}

				table.Add(string.Join(", ", values) + ",");
			}

			int typeChunks = (types.Count + MaxTypesPerMethod - 1) / MaxTypesPerMethod;

			code.Line();
			code.Line("private static " + TypeEntry + "[] CreateTypes() =>");
			code.Indent();
			code.Line(Table + ".CreateEntries(");
			code.Indent();
			code.Line("CreateTypeTable(),");
			code.Line("new " + ReducerFactory + "[]");
			code.Open();
			foreach (int entryIndex in reducerFactories)
				code.Line("new " + ReducerFactory + "(CreateReducers" + entryIndex + "),");
			code.Close("},");
			code.Line("new " + EffectFactory + "[]");
			code.Open();
			foreach (int entryIndex in effectFactories)
				code.Line("new " + EffectFactory + "(CreateEffects" + entryIndex + "),");
			code.Close("},");
			code.Line(states.FeatureStates.Count > 0 ? "new global::System.Func<int, " + IFeature + ">(CreateFeature)," : "null,");
			code.Line(states.StateTypes.Count > 0 ? "new global::System.Action<" + IFeature + ", object, int>(AddReducer)," : "null,");
			code.Line("new int[]");
			code.Open();
			foreach (string line in table)
				code.Line(line);
			code.Close("});");
			code.Unindent();
			code.Unindent();

			code.Line();
			code.Line("private static global::System.Type[] CreateTypeTable()");
			code.Open();
			code.Line("var types = new global::System.Type[" + types.Count + "];");
			for (int chunk = 0; chunk < typeChunks; chunk++)
				code.Line("AddTypes" + chunk + "(types);");
			code.Line("return types;");
			code.Close();

			for (int chunk = 0; chunk < typeChunks; chunk++)
			{
				code.Line();
				code.Line("private static void AddTypes" + chunk + "(global::System.Type[] types)");
				code.Open();
				for (int i = chunk * MaxTypesPerMethod; i < Math.Min(types.Count, (chunk + 1) * MaxTypesPerMethod); i++)
					code.Line("types[" + i + "] = typeof(" + types[i] + ");");
				code.Close();
			}

			for (int i = 0; i < model.Entries.Count; i++)
			{
				TypeEntryModel entry = model.Entries[i];
				if (entry.ReducerMethods.Count > 0)
				{
					code.Line();
					EmitReducerFactory(code, i, entry.ReducerMethods);
				}
				if (entry.EffectMethods.Count > 0)
				{
					code.Line();
					EmitEffectFactory(code, i, entry.EffectMethods);
				}
			}

			if (states.FeatureStates.Count > 0)
			{
				code.Line();
				EmitCreateFeature(code, states);
				code.Line();
				EmitCreateInitialState(code, states);
			}

			if (states.StateTypes.Count > 0)
			{
				code.Line();
				EmitAddReducer(code, states);
			}
		}

		/// <summary>The GeneratedRegistrationTable flags of an entry.</summary>
		private static int GetFlags(TypeEntryModel entry) =>
			(entry.IsMiddleware ? 1 : 0)
			| (entry.IsEffectClass ? 2 : 0)
			| (entry.FeatureClass is not null ? 4 : 0)
			| (entry.FeatureState is not null ? 8 : 0)
			| (entry.ReducerClassStateType is not null ? 16 : 0);

		private static void EmitReducerFactory(CodeWriter code, int entryIndex, List<ReducerMethodModel> reducers)
		{
			code.Line("private static object CreateReducers" + entryIndex + "(object host, int index)");
			code.Open();
			code.Line("switch (index)");
			code.Open();
			for (int i = 0; i < reducers.Count; i++)
			{
				ReducerMethodModel reducer = reducers[i];
				string factory = reducer.TakesAction ? "Reducer" : "ReducerWithoutAction";
				code.Line(
					"case " + i + ": return " + Wrappers + "." + factory + "<" + reducer.StateType + ", " + reducer.ActionType + ">("
					+ reducer.MethodGroup + ");");
			}
			code.Line("default: throw new global::System.ArgumentOutOfRangeException(\"index\");");
			code.Close();
			code.Close();
		}

		private static void EmitEffectFactory(CodeWriter code, int entryIndex, List<EffectMethodModel> effects)
		{
			code.Line("private static " + IEffect + " CreateEffects" + entryIndex + "(object host, int index)");
			code.Open();
			code.Line("switch (index)");
			code.Open();
			for (int i = 0; i < effects.Count; i++)
			{
				EffectMethodModel effect = effects[i];
				string factory = effect.TakesAction ? "Effect" : "EffectWithoutAction";
				code.Line("case " + i + ": return " + Wrappers + "." + factory + "<" + effect.ActionType + ">(" + effect.MethodGroup + ");");
			}
			code.Line("default: throw new global::System.ArgumentOutOfRangeException(\"index\");");
			code.Close();
			code.Close();
		}

		private static void EmitCreateFeature(CodeWriter code, StateTable states)
		{
			code.Line("private static " + IFeature + " CreateFeature(int stateIndex)");
			code.Open();
			code.Line("switch (stateIndex)");
			code.Open();
			foreach (FeatureStateModel state in states.FeatureStates)
			{
				int index = states[state.StateType];
				string settings = FeatureSettings(state);
				if (state.InitialStateKind == InitialStateKind.ReflectedFactoryMethod)
				{
					// The factory method is not callable from here; found the way FeatureStateInfo finds it
					code.Line("case " + index + ":");
					code.Open();
					EmitReflectedFactory(code, state);
					code.Line(
						"return " + Wrappers + ".FeatureState<" + state.StateType + ">(" + settings + ", () => (" + state.StateType
						+ ")createInitialState());");
					code.Close();
				}
				else
				{
					code.Line(
						"case " + index + ": return " + Wrappers + ".FeatureState<" + state.StateType + ">(" + settings
						+ ", CreateInitialState, " + index + ");");
				}
			}
			code.Line("default: throw new global::System.ArgumentOutOfRangeException(\"stateIndex\");");
			code.Close();
			code.Close();
		}

		private static void EmitCreateInitialState(CodeWriter code, StateTable states)
		{
			code.Line("private static object CreateInitialState(int stateIndex)");
			code.Open();
			code.Line("switch (stateIndex)");
			code.Open();
			foreach (FeatureStateModel state in states.FeatureStates)
			{
				string? create = state.InitialStateKind switch
				{
					InitialStateKind.Constructor => "new " + state.StateType + "()",
					// The state's constructor is not callable from here (non-public, abstract type or required members)
					InitialStateKind.ActivatorConstructor =>
						"global::System.Activator.CreateInstance(typeof(" + state.StateType + "), nonPublic: true)",
					InitialStateKind.FactoryMethod => state.FactoryMethodName + "()",
					_ => null
				};
				if (create is not null)
					code.Line("case " + states[state.StateType] + ": return " + create + ";");
			}
			code.Line("default: throw new global::System.ArgumentOutOfRangeException(\"stateIndex\");");
			code.Close();
			code.Close();
		}

		private static void EmitAddReducer(CodeWriter code, StateTable states)
		{
			code.Line("private static void AddReducer(" + IFeature + " feature, object reducer, int stateIndex)");
			code.Open();
			code.Line("switch (stateIndex)");
			code.Open();
			for (int i = 0; i < states.StateTypes.Count; i++)
			{
				string stateType = states.StateTypes[i];
				code.Line(
					"case " + i + ": ((" + IFeature + "<" + stateType + ">)feature).AddReducer((global::Fluxor.IReducer<" + stateType
					+ ">)reducer); return;");
			}
			code.Line("default: throw new global::System.ArgumentOutOfRangeException(\"stateIndex\");");
			code.Close();
			code.Close();
		}
	}

	/// <summary>Declares <c>createInitialState</c>, the factory method found the way FeatureStateInfo finds it.</summary>
	private static void EmitReflectedFactory(CodeWriter code, FeatureStateModel state)
	{
		code.Line("var createInitialState = (global::System.Func<object>)typeof(" + state.StateType + ")");
		code.Indent();
		code.Line(".GetMethod(");
		code.Indent();
		code.Line(SymbolDisplay.FormatLiteral(state.FactoryMethodName!, quote: true) + ",");
		code.Line(
			"global::System.Reflection.BindingFlags.Static | global::System.Reflection.BindingFlags.Public"
			+ " | global::System.Reflection.BindingFlags.NonPublic)");
		code.Unindent();
		code.Line(".CreateDelegate(typeof(global::System.Func<object>));");
		code.Unindent();
	}

	private static string FeatureSettings(FeatureStateModel state) =>
		(state.Name is null ? "null" : SymbolDisplay.FormatLiteral(state.Name, quote: true))
		+ ", " + state.MaximumStateChangedNotificationsPerSecond
		+ ", " + Bool(state.DebuggerBrowsable);

	private static string Bool(bool value) => value ? "true" : "false";

	private sealed class CodeWriter
	{
		private readonly List<string> Lines = new();
		private int IndentLevel;

		public void Line(string text = "") =>
			Lines.Add(text.Length == 0 ? "" : new string('\t', IndentLevel) + text);

		public void Indent() => IndentLevel++;
		public void Unindent() => IndentLevel--;

		public void Open()
		{
			Line("{");
			IndentLevel++;
		}

		public void Close(string text = "}")
		{
			IndentLevel--;
			Line(text);
		}

		public override string ToString()
		{
			var builder = new StringBuilder();
			foreach (string line in Lines)
				builder.Append(line).Append('\n');
			return builder.ToString();
		}
	}
}
